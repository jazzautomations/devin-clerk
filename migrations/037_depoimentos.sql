-- 037 — depoimento de time (spec 046, aposta da 044 §1.2).
--
-- Quem fez time com alguém numa edição escreve sobre essa pessoa; ela aceita
-- ou recusa. Só o aceito aparece no perfil. memberId é quem recebe (dono da
-- linha), authorId quem escreveu e está em PEER_COLUMNS (lib/privacy.ts): se
-- qualquer um dos dois excluir a conta, o texto some.
--
-- status:
--   pendente  esperando o dono decidir (só ele e o autor veem)
--   aceito    aparece no perfil
--   recusado  recusa silenciosa: o autor continua vendo "enviado"
--   oculto    o dono aceitou e depois tirou do perfil
--   removido  quem trata a denúncia tirou do ar: some pros dois lados, o dono
--             não traz de volta e o autor não reescreve (o UNIQUE segura)
-- Editar um aceito volta pra pendente (lib/testimonials.ts). Um depoimento
-- por autor, pessoa e edição. teamId fica nulo se o time for apagado.

CREATE TABLE team_testimonials (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "authorId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "teamId" INTEGER REFERENCES teams("id") ON DELETE SET NULL,
  "body" TEXT NOT NULL CHECK (char_length("body") BETWEEN 40 AND 600),
  "status" TEXT NOT NULL DEFAULT 'pendente' CHECK ("status" IN ('pendente', 'aceito', 'recusado', 'oculto', 'removido')),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "updatedAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "acceptedAt" TEXT,
  UNIQUE ("authorId", "memberId", "hackathonId"),
  CHECK ("authorId" <> "memberId")
);
-- perfil e caixa do dono: por pessoa e status
CREATE INDEX idx_team_testimonials_member ON team_testimonials ("memberId", "status");
-- "enviados" do autor
CREATE INDEX idx_team_testimonials_author ON team_testimonials ("authorId");
