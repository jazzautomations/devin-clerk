-- 007 — candidatura por tipo numa edição: voluntário, mentor, jurado
-- (spec 033, frente E). Além de se inscrever como participante, a pessoa
-- pode se candidatar pra ajudar. O organizador abre os tipos que quiser,
-- monta um formulário próprio por tipo e aprova/recusa; aprovar concede o
-- papel da edição (voluntario→staff, mentor→mentor, jurado→jurado).

-- tipos abertos por edição: linha presente = aberto. Tabela (e não coluna
-- em hackathons) porque é conjunto pequeno com dono e data de abertura.
CREATE TABLE edition_open_kinds (
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "kind" TEXT NOT NULL CHECK ("kind" IN ('voluntario', 'mentor', 'jurado')),
  "openedBy" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("hackathonId", "kind")
);

-- uma candidatura por pessoa por tipo por edição. A decisão é final e fica
-- registrada (recusada não some nem reabre); note = observação interna de
-- quem decidiu.
CREATE TABLE role_applications (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "kind" TEXT NOT NULL CHECK ("kind" IN ('voluntario', 'mentor', 'jurado')),
  "status" TEXT NOT NULL DEFAULT 'pending' CHECK ("status" IN ('pending', 'approved', 'rejected')),
  "note" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "reviewedAt" TEXT,
  "reviewedBy" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  UNIQUE ("hackathonId", "memberId", "kind")
);
CREATE INDEX idx_role_applications_queue ON role_applications ("hackathonId", "kind", "status");
CREATE INDEX idx_role_applications_member ON role_applications ("memberId", "hackathonId");

-- formulário por público: a mesma tabela de perguntas (tipos, versões
-- congeladas, arquivar, ordem) serve participante e cada tipo de candidatura.
-- Linhas antigas = participante.
ALTER TABLE edition_questions ADD COLUMN "audience" TEXT NOT NULL DEFAULT 'participante'
  CHECK ("audience" IN ('participante', 'voluntario', 'mentor', 'jurado'));
DROP INDEX idx_edition_questions_hackathon;
CREATE INDEX idx_edition_questions_hackathon
  ON edition_questions ("hackathonId", "audience", "archived", "position");

-- respostas da candidatura em tabela própria (espelho de
-- registration_answers): a FK pra candidatura dá o CASCADE certo (retirar
-- a candidatura apaga as respostas), a PK continua simples e a FK composta
-- pra edition_question_versions mantém a versão congelada que a pessoa viu.
-- Reaproveitar registration_answers exigiria registrationId nulo + coluna
-- polimórfica e quebraria a PK atual.
CREATE TABLE role_application_answers (
  "applicationId" INTEGER NOT NULL REFERENCES role_applications("id") ON DELETE CASCADE,
  "questionId" INTEGER NOT NULL,
  "questionVersion" INTEGER NOT NULL,
  "value" TEXT NOT NULL,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("applicationId", "questionId"),
  FOREIGN KEY ("questionId", "questionVersion")
    REFERENCES edition_question_versions ("questionId", "version") ON DELETE CASCADE
);
CREATE INDEX idx_role_application_answers_question ON role_application_answers ("questionId");

-- consentimento por finalidade: o aceite de candidatura (avaliar a
-- candidatura e organizar a atuação) não vale como aceite de inscrição de
-- participante e vice-versa. Linhas antigas = participante.
ALTER TABLE consents ADD COLUMN "scope" TEXT NOT NULL DEFAULT 'participante'
  CHECK ("scope" IN ('participante', 'voluntario', 'mentor', 'jurado'));
