-- 016 — acabamentos do QA ponta a ponta (frente N).

-- (6) lista pública de inscritos × consentimento. O aceite LGPD da
-- inscrição (lib/registrationForm consentPurpose) cobre só "organizar o
-- evento" — não há base pra expor nome/@ de quem se inscreveu. Aparecer
-- na lista pública da edição vira opt-in explícito por inscrição; o padrão
-- é NÃO aparecer. Inscrições antigas ficam 0 (ninguém consentiu com isso).
ALTER TABLE registrations ADD COLUMN "publicListing" INTEGER NOT NULL DEFAULT 0
  CHECK ("publicListing" IN (0, 1));

-- (5) quórum da escolha do público (voto ao vivo no palco): abaixo de N
-- votos na edição o ranking/prêmio não aparece — "votação sem quórum".
ALTER TABLE hackathons ADD COLUMN "audienceMinVotes" INTEGER NOT NULL DEFAULT 10
  CHECK ("audienceMinVotes" BETWEEN 0 AND 100000);

-- (4) aceite de membro de time. Convidar não põe ninguém no time: a linha
-- de team_members só nasce quando o convidado aceita. Tabela separada de
-- propósito — team_members segue significando "está no time" pra todos os
-- leitores (arquivo, júri, certificados, voto, palco), então os membros
-- que já existem continuam aceitos sem tocar em dado nenhum.
CREATE TABLE team_invites (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "invitedBy" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "status" TEXT NOT NULL DEFAULT 'pending'
    CHECK ("status" IN ('pending', 'accepted', 'declined', 'cancelled')),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "respondedAt" TEXT,
  UNIQUE ("teamId", "memberId")
);
CREATE INDEX idx_team_invites_member ON team_invites ("memberId", "hackathonId", "status");

-- (8) username: troca única pelo perfil + redirect do antigo. O antigo
-- fica reservado (ninguém assume o @ de outra pessoa) e /u/antigo responde
-- 308 pro novo. Certificados usam código próprio (/c/[code]) e memberId.
ALTER TABLE members ADD COLUMN "usernameChangedAt" TEXT;
CREATE TABLE username_redirects (
  "oldUsername" TEXT PRIMARY KEY,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_username_redirects_member ON username_redirects ("memberId");
