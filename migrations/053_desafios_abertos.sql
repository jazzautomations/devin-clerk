-- 053 — desafios abertos entre edições (spec 046, onda 5).
--
-- Dono ou organizador de comunidade publica um desafio com prazo; quem tem
-- conta entrega com um projeto do HackaHub (teamId) ou um repo; quem criou
-- escolhe 1º a 3º e o resultado fica público.
--
-- Tabela própria, separada de challenges (001): aquela é o catálogo de
-- desafio de patrocinador preso à edição (project_challenges, júri,
-- premiação). Desafio aberto não tem edição, inscrição nem júri.
--
-- "encerrado" não é status gravado: é status 'aberto' com o prazo vencido,
-- calculado na leitura (sem cron). O prazo é texto no formato de
-- lib/eventTime.ts ("2026-11-14T23:59:00-03:00"), lido com to_ts (019).
--
-- LGPD (lib/privacy.ts): entries.memberId é coluna de dono, a entrega some
-- quando a pessoa exclui a conta. createdBy é ator e fica apontando pra
-- linha anonimizada, o desafio continua de pé.

CREATE TABLE open_challenges (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "communityId" INTEGER NOT NULL REFERENCES communities("id") ON DELETE CASCADE,
  "sponsorName" TEXT CHECK ("sponsorName" IS NULL OR char_length("sponsorName") BETWEEN 1 AND 80),
  "title" TEXT NOT NULL CHECK (char_length("title") BETWEEN 1 AND 100),
  "brief" TEXT NOT NULL CHECK (char_length("brief") BETWEEN 1 AND 3000),
  "rules" TEXT CHECK ("rules" IS NULL OR char_length("rules") <= 3000),
  "prize" TEXT CHECK ("prize" IS NULL OR char_length("prize") <= 200),
  "deadline" TEXT NOT NULL,
  "status" TEXT NOT NULL DEFAULT 'rascunho' CHECK ("status" IN ('rascunho', 'aberto', 'resultado')),
  "createdBy" INTEGER NOT NULL REFERENCES members("id"),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "publishedAt" TEXT,
  "resultAt" TEXT
);
-- /desafios e o filtro por comunidade
CREATE INDEX idx_open_challenges_community ON open_challenges ("communityId", "status");
CREATE INDEX idx_open_challenges_status ON open_challenges ("status", "deadline");

CREATE TABLE open_challenge_entries (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "challengeId" INTEGER NOT NULL REFERENCES open_challenges("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "teamId" INTEGER REFERENCES teams("id") ON DELETE SET NULL,
  "repoUrl" TEXT CHECK ("repoUrl" IS NULL OR char_length("repoUrl") <= 300),
  "demoUrl" TEXT CHECK ("demoUrl" IS NULL OR char_length("demoUrl") <= 300),
  "summary" TEXT NOT NULL CHECK (char_length("summary") BETWEEN 1 AND 1000),
  "submittedAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "place" INTEGER CHECK ("place" IS NULL OR "place" BETWEEN 1 AND 3),
  UNIQUE ("challengeId", "memberId")
);
-- cada colocação sai uma vez por desafio
CREATE UNIQUE INDEX idx_open_challenge_entries_place ON open_challenge_entries ("challengeId", "place") WHERE "place" IS NOT NULL;
CREATE INDEX idx_open_challenge_entries_member ON open_challenge_entries ("memberId");
