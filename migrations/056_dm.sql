-- 056 — mensagem direta com trava (spec 046, onda 6: dm-com-trava).
--
-- DM transforma leitor em conexão, mas aberta pra todo mundo vira spam. A
-- trava (lib/dm.ts, canMessage) só deixa conversar quem já tem laço: seguir
-- mútuo, mesmo time (lib/evidence.ts), encontro confirmado (050) ou vaga
-- aceita (045). Sem laço, a pessoa manda UM pedido de até 280 e o outro
-- aceita ou recusa. Bloqueio é member_blocks (032) e denúncia é reports
-- (targetType 'dm', com o snapshot da mensagem): sem dm_blocks nem
-- dm_reports.
--
-- dm_threads guarda o PAR em ordem crescente (memberId < peerId), igual a
-- encounters: uma thread por par pra sempre. O status marca se a conversa
-- nasceu livre ('aberta'), se é pedido esperando resposta ('pedido') ou se
-- o pedido foi recusado ('recusada' — quem pediu espera 30 dias pra tentar
-- de novo). `requestedBy` é quem fez o pedido (NULL em thread que nasceu
-- livre); `declinedAt` guarda a recusa pra regra dos 30 dias.
--
-- LGPD (lib/privacy.ts): memberId e peerId seguem a convenção de relação
-- entre duas pessoas — memberId é OWNER_COLUMNS e peerId já está em
-- PEER_COLUMNS, então excluir a conta de QUALQUER lado apaga a thread com
-- as mensagens e as leituras (cascade do DELETE da linha). Em dm_messages
-- e dm_reads, memberId é o dono da linha (apaga também). `requestedBy` é
-- ator dentro da linha do par: não precisa de regra própria porque a linha
-- inteira some com o par.

CREATE TABLE dm_threads (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- o par em ordem crescente: UNIQUE(memberId, peerId) = uma thread por par
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "peerId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "status" TEXT NOT NULL DEFAULT 'aberta'
    CHECK ("status" IN ('aberta', 'pedido', 'recusada')),
  "requestedBy" INTEGER REFERENCES members("id") ON DELETE CASCADE,
  "declinedAt" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "lastMessageAt" TEXT,
  UNIQUE ("memberId", "peerId"),
  CHECK ("memberId" < "peerId")
);
CREATE INDEX idx_dm_threads_member ON dm_threads ("memberId", "lastMessageAt");
CREATE INDEX idx_dm_threads_peer ON dm_threads ("peerId", "lastMessageAt");

-- corpo de até 2000 no CHECK (a trava fina de 280 do pedido fica no código)
CREATE TABLE dm_messages (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "threadId" INTEGER NOT NULL REFERENCES dm_threads("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "body" TEXT NOT NULL CHECK (char_length("body") BETWEEN 1 AND 2000),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_dm_messages_thread ON dm_messages ("threadId", "id");
CREATE INDEX idx_dm_messages_author ON dm_messages ("memberId");

-- até onde cada pessoa leu: a notificação 'dm' e o contador do header saem
-- da diferença entre lastReadId e a última mensagem do outro lado
CREATE TABLE dm_reads (
  "threadId" INTEGER NOT NULL REFERENCES dm_threads("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "lastReadId" INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY ("threadId", "memberId")
);
