-- 031 — base de confiança da rede social (spec 046, evidencia-e-lgpd).
--
-- 1) members."lastSeenAt": quando a pessoa usou o HackaHub logada pela
--    última vez (gravado no máximo 1x por hora em lib/session.ts). O digest e
--    as métricas usam pra saber quem voltou. Conta excluída zera (ANONYMIZE
--    em lib/privacy.ts) e fica fora do backfill. Quem já existe parte da data
--    do cadastro.
ALTER TABLE members ADD COLUMN IF NOT EXISTS "lastSeenAt" TEXT;
UPDATE members SET "lastSeenAt" = "createdAt"
  WHERE "lastSeenAt" IS NULL AND "clerkId" NOT LIKE 'deleted:%';

-- 2) notifications."actorId": quem causou a notificação, por id. O
--    actorUsername continua (texto congelado pra exibir), mas a regra "1 por
--    par" (alreadyNotified) não pode furar quando a pessoa troca de @.
--    O histórico casa pelo @ atual e depois pelo @ antigo (username_redirects
--    guarda o @ antigo reservado pra mesma pessoa); o que não casar fica NULL.
--    IF NOT EXISTS: a branch de bloqueio e denúncia também cria essa coluna;
--    quem entrar depois não pode derrubar o boot.
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS "actorId" INTEGER REFERENCES members("id") ON DELETE SET NULL;
UPDATE notifications n SET "actorId" = m."id"
  FROM members m
  WHERE n."actorId" IS NULL AND n."actorUsername" IS NOT NULL AND m."username" = n."actorUsername";
UPDATE notifications n SET "actorId" = r."memberId"
  FROM username_redirects r
  WHERE n."actorId" IS NULL AND r."oldUsername" = n."actorUsername";
CREATE INDEX IF NOT EXISTS idx_notifications_actor_pair ON notifications ("memberId", "type", "actorId", "href");

-- 3) edition_role_revocations: papel tirado de alguém numa edição. A regra
--    antifarm de lib/evidence.ts ("quem organiza não ganha presença, entrega
--    nem prêmio na própria edição") olha quem FOI organizador, não só quem é
--    hoje: senão outro organizador tira o papel depois do evento e os fatos
--    aparecem. Só cresce (revokeEditionRole grava aqui).
CREATE TABLE IF NOT EXISTS edition_role_revocations (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "role" TEXT NOT NULL CHECK ("role" IN ('organizador','staff','mentor','jurado')),
  "revokedAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX IF NOT EXISTS idx_edition_role_revocations_ed ON edition_role_revocations ("hackathonId", "memberId", "role");
