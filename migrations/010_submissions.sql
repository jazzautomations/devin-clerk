  SELECT conname INTO c FROM pg_constraint
   WHERE conrelid = 'certificates'::regclass AND contype = 'u';
  IF c IS NOT NULL THEN
    EXECUTE format('ALTER TABLE certificates DROP CONSTRAINT %I', c);
  END IF;
END $$;
