-- 010 — entrega de projeto de verdade (spec 034 §5). Até aqui o projeto do
-- time era editável até o fim e ninguém sabia quem tinha entregado. Agora:
-- prazos por edição (no servidor, com tolerância), rascunho → enviado →
-- travado com snapshot imutável por versão, log de eventos, desafios
-- marcados pelo time e categorias de prêmio ligadas ao júri.
--
-- Edição sem "submissionDeadline" continua no modo antigo (sem trava, júri
-- vê todo time) — é o que mantém o arquivo das edições passadas de pé.

-- prazos (UTC, mesmo formato TEXT do resto) + o que é obrigatório na entrega
ALTER TABLE hackathons ADD COLUMN "teamFormationDeadline" TEXT;
ALTER TABLE hackathons ADD COLUMN "submissionOpensAt" TEXT;
ALTER TABLE hackathons ADD COLUMN "submissionDeadline" TEXT;
ALTER TABLE hackathons ADD COLUMN "submissionGraceMinutes" INTEGER NOT NULL DEFAULT 0
  CHECK ("submissionGraceMinutes" BETWEEN 0 AND 10);
ALTER TABLE hackathons ADD COLUMN "juryDeadline" TEXT;
ALTER TABLE hackathons ADD COLUMN "requireRepo" INTEGER NOT NULL DEFAULT 1;
ALTER TABLE hackathons ADD COLUMN "requireVideo" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE hackathons ADD COLUMN "requireSlides" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE hackathons ADD COLUMN "requireAiUsage" INTEGER NOT NULL DEFAULT 0;
-- depois do prazo, All Entries mostra o conteúdo (1) ou só nome + status (0)
ALTER TABLE hackathons ADD COLUMN "entriesShowContent" INTEGER NOT NULL DEFAULT 1;

-- campos novos do projeto. technologies/links/socialPosts são JSON em TEXT
-- (mesmo padrão de tags/skills). stageVideoUrl é da organização; afterNotes
-- é a seção "depois do hackathon", fora do snapshot e do julgamento.
ALTER TABLE team_projects ADD COLUMN "tagline" TEXT;
ALTER TABLE team_projects ADD COLUMN "priorWork" TEXT;
ALTER TABLE team_projects ADD COLUMN "technologies" TEXT NOT NULL DEFAULT '[]';
ALTER TABLE team_projects ADD COLUMN "links" TEXT NOT NULL DEFAULT '[]';
ALTER TABLE team_projects ADD COLUMN "socialPosts" TEXT NOT NULL DEFAULT '[]';
ALTER TABLE team_projects ADD COLUMN "slidesUrl" TEXT;
ALTER TABLE team_projects ADD COLUMN "aiUsage" TEXT;
ALTER TABLE team_projects ADD COLUMN "stageVideoUrl" TEXT;
ALTER TABLE team_projects ADD COLUMN "afterNotes" TEXT;
ALTER TABLE team_projects ADD COLUMN "lastSavedAt" TEXT;

-- reabertura pelo organizador vale até reopenedUntil; finalista = rodada
-- opcional (preliminar → final)
ALTER TABLE teams ADD COLUMN "reopenedUntil" TEXT;
ALTER TABLE teams ADD COLUMN "finalist" INTEGER NOT NULL DEFAULT 0;

-- cada envio vira uma versão imutável; o júri avalia a última enviada até o
-- prazo (mesmo que o time seja reaberto e envie de novo depois)
CREATE TABLE project_submissions (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "version" INTEGER NOT NULL,
  "snapshot" TEXT NOT NULL,
  "submittedBy" INTEGER REFERENCES members("id"),
  "submittedAt" TEXT NOT NULL DEFAULT sqlite_now(),
  UNIQUE ("teamId", "version")
);
CREATE INDEX idx_project_submissions_team ON project_submissions ("teamId", "submittedAt");

-- log: enviado, reaberto, vídeo do palco, lembretes e aviso de trava.
-- Lembrete/trava é 1 por time (índice parcial) — o cron pode rodar à vontade.
CREATE TABLE submission_events (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id"),
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "kind" TEXT NOT NULL CHECK ("kind" IN (
    'enviado', 'reaberto', 'palco', 'lembrete_24h', 'lembrete_3h', 'lembrete_30m', 'travado')),
  "memberId" INTEGER REFERENCES members("id"),
  "version" INTEGER,
  "reason" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  CHECK ("kind" <> 'reaberto' OR length(trim(coalesce("reason", ''))) > 0)
);
CREATE INDEX idx_submission_events_hackathon ON submission_events ("hackathonId", "id" DESC);
CREATE UNIQUE INDEX idx_submission_events_once ON submission_events ("teamId", "kind")
  WHERE "kind" IN ('lembrete_24h', 'lembrete_3h', 'lembrete_30m', 'travado');

-- desafios patrocinados que o time disputa (0..N)
CREATE TABLE project_challenges (
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "challengeId" TEXT NOT NULL REFERENCES challenges("id") ON DELETE CASCADE,
  PRIMARY KEY ("teamId", "challengeId")
);
CREATE INDEX idx_project_challenges_challenge ON project_challenges ("challengeId");

-- categorias de prêmio: geral (ranking de todos os entregues) ou desafio
-- (só quem marcou o desafio). places = quantas posições premiam.
CREATE TABLE prize_categories (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id"),
  "kind" TEXT NOT NULL CHECK ("kind" IN ('geral', 'desafio')),
  "name" TEXT NOT NULL,
  "challengeId" TEXT REFERENCES challenges("id") ON DELETE CASCADE,
  "places" INTEGER NOT NULL DEFAULT 1 CHECK ("places" BETWEEN 1 AND 10),
  "finalistsOnly" INTEGER NOT NULL DEFAULT 0,
  "position" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  CHECK (("kind" = 'desafio') = ("challengeId" IS NOT NULL))
);
CREATE INDEX idx_prize_categories_hackathon ON prize_categories ("hackathonId", "position");

-- gravado na publicação do resultado (refazer a publicação regrava)
CREATE TABLE prize_winners (
  "categoryId" INTEGER NOT NULL REFERENCES prize_categories("id") ON DELETE CASCADE,
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "place" INTEGER NOT NULL,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("categoryId", "teamId")
);
CREATE INDEX idx_prize_winners_team ON prize_winners ("teamId");

-- certificado de premiação passa a ser por categoria: a mesma pessoa pode
-- levar o geral e um desafio. Sem categoria (modo antigo) = NULL → 0.
ALTER TABLE certificates ADD COLUMN "prizeCategoryId" INTEGER REFERENCES prize_categories("id") ON DELETE SET NULL;
