-- 055 — copilot do arquivo (spec 046, onda 6: copilot-do-arquivo).
--
-- Log das perguntas feitas ao copilot: o que a pessoa perguntou, a intenção
-- que as regras detectaram, quantos fatos do arquivo voltaram, se o resumo
-- passou pelo LLM e o voto "ajudou?". Não tem resposta gravada: o resumo é
-- gerado na hora e nunca vira registro (a IA não produz fato, só apresenta).
--
-- LGPD (lib/privacy.ts): memberId é coluna de dono — a exclusão da conta
-- apaga as perguntas junto, pela varredura automática de FK pra members.
-- A poda de 90 dias roda no próprio insert (lib/copilot/retrieve.ts), sem
-- cron: pergunta de arquivo é contexto, não histórico.

CREATE TABLE copilot_queries (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "question" TEXT NOT NULL CHECK (char_length("question") BETWEEN 1 AND 300),
  "intent" TEXT NOT NULL CHECK ("intent" IN ('similar','stack','edicao','regras','busca')),
  "resultCount" INTEGER NOT NULL DEFAULT 0,
  "usedLlm" INTEGER NOT NULL DEFAULT 0,
  -- 1 = ajudou, 0 = não; NULL = sem voto (feedback é opcional)
  "helpful" INTEGER CHECK ("helpful" IN (0, 1)),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_copilot_queries_member ON copilot_queries ("memberId", "id" DESC);
-- a poda por data roda varrendo este índice
CREATE INDEX idx_copilot_queries_created ON copilot_queries ("createdAt");
