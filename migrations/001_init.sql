-- datas gravadas em dois formatos ("YYYY-MM-DD HH:MM:SS" UTC e ISO com offset
-- do scraper); to_ts normaliza pra comparar. Texto inválido vira NULL.
CREATE OR REPLACE FUNCTION to_ts(v text) RETURNS timestamptz
  LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  IF v IS NULL OR v = '' THEN RETURN NULL; END IF;
  IF v ~ '(Z|[+-]\d\d:?\d\d)$' THEN RETURN v::timestamptz; END IF;
  RETURN (v || ' UTC')::timestamptz;
EXCEPTION WHEN others THEN
  RETURN NULL;
END $$;
