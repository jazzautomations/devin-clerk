-- 001 — schema consolidado (era espalhado em CREATE/ensureColumn nos lib/*.ts
-- do tempo do SQLite). Identificadores camelCase entre aspas: o código e as
-- respostas da API usam camelCase e o Postgres minusculiza o que não é citado.
-- Datas continuam TEXT "YYYY-MM-DD HH:MM:SS" (UTC) — mesmo formato que o app
-- já compara como string; migrar pra timestamptz é passo separado.

CREATE OR REPLACE FUNCTION sqlite_now() RETURNS text
  LANGUAGE sql STABLE
  AS $$ SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

-- datetime('now', '-40 days') do sqlite → sqlite_now('-40 days')
CREATE OR REPLACE FUNCTION sqlite_now(shift text) RETURNS text
  LANGUAGE sql STABLE
  AS $$ SELECT to_char((now() AT TIME ZONE 'utc') + shift::interval, 'YYYY-MM-DD HH24:MI:SS') $$;

