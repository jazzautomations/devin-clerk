-- 036 — vitrine do projeto (spec 046, onda 1, vitrine-de-projeto).
--
-- /p/[teamId] vira a página permanente do projeto. Reaproveita o que já
-- existe: description é "O que faz", tagline segue como subtítulo,
-- technologies (JSON) continua sendo a fonte da stack e afterNotes vira a
-- seção "Depois do hackathon". O que entra aqui é a história (editável
-- depois da trava, fora do que o júri avalia), a capa, a galeria, o papel de
-- cada integrante e um índice de tags pra /projetos?tech=.
-- Tudo idempotente: rodar de novo não quebra nem duplica.

ALTER TABLE team_projects ADD COLUMN IF NOT EXISTS "inspiration" TEXT;
ALTER TABLE team_projects ADD COLUMN IF NOT EXISTS "howBuilt" TEXT;
ALTER TABLE team_projects ADD COLUMN IF NOT EXISTS "challenges" TEXT;
ALTER TABLE team_projects ADD COLUMN IF NOT EXISTS "learned" TEXT;
ALTER TABLE team_projects ADD COLUMN IF NOT EXISTS "coverUrl" TEXT;

-- o que a pessoa fez no time (até 80, validado no código). Texto pessoal:
-- a exclusão de conta apaga junto com o @ (lib/privacy.ts).
ALTER TABLE team_members ADD COLUMN IF NOT EXISTS "role" TEXT;

-- índice derivado de team_projects.technologies; o editor reescreve no save
-- (syncProjectTech em lib/entries.ts), na mesma transação
CREATE TABLE IF NOT EXISTS project_tech (
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "tag" TEXT NOT NULL CHECK ("tag" ~ '^[a-z0-9][a-z0-9.+#-]{0,29}$'),
  PRIMARY KEY ("teamId", "tag")
);
CREATE INDEX IF NOT EXISTS idx_project_tech_tag ON project_tech ("tag");

-- galeria por URL https (sem armazenamento próprio até existir moderação de
-- imagem). Até 6 por projeto, validado no código.
CREATE TABLE IF NOT EXISTS project_media (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "url" TEXT NOT NULL CHECK ("url" ~ '^https://'),
  "caption" TEXT,
  "position" INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_project_media_team ON project_media ("teamId", "position");

-- backfill do índice: projeto antigo aparece em /projetos?tech= sem precisar
-- salvar de novo. Mesma normalização de lib/techTags.ts (minúsculas, espaço
-- vira hífen, apelidos); o acerto fino vem no próximo save. JSON quebrado
-- numa linha não derruba a migration: a linha fica sem tag.
DO $$
DECLARE
  r RECORD;
  raw TEXT;
  t TEXT;
BEGIN
  FOR r IN SELECT "teamId", "technologies" FROM team_projects LOOP
    BEGIN
      FOR raw IN SELECT jsonb_array_elements_text(r."technologies"::jsonb) LOOP
        t := lower(trim(raw));
        t := translate(t, 'áàâãäéèêëíìîïóòôõöúùûüçñ', 'aaaaaeeeeiiiiooooouuuucn');
        t := regexp_replace(t, '\s+', '-', 'g');
        t := regexp_replace(t, '[^a-z0-9.+#-]', '', 'g');
        t := regexp_replace(t, '^[^a-z0-9]+', '');
        t := regexp_replace(t, '-+$', '');
        t := CASE t
          WHEN 'next.js' THEN 'nextjs'
          WHEN 'next' THEN 'nextjs'
          WHEN 'js' THEN 'javascript'
          WHEN 'ts' THEN 'typescript'
          WHEN 'react.js' THEN 'react'
          WHEN 'reactjs' THEN 'react'
          WHEN 'node' THEN 'nodejs'
          WHEN 'node.js' THEN 'nodejs'
          WHEN 'py' THEN 'python'
          WHEN 'postgres' THEN 'postgresql'
          WHEN 'vue.js' THEN 'vue'
          WHEN 'vuejs' THEN 'vue'
          WHEN 'golang' THEN 'go'
          ELSE t
        END;
        t := left(t, 30);
        IF t ~ '^[a-z0-9][a-z0-9.+#-]{0,29}$' THEN
          INSERT INTO project_tech ("teamId", "tag") VALUES (r."teamId", t) ON CONFLICT DO NOTHING;
        END IF;
      END LOOP;
    EXCEPTION WHEN others THEN
      NULL;
    END;
  END LOOP;
END $$;
