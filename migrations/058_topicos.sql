-- 058 — tópicos da comunidade (spec 046, onda 1).
--
-- Cada comunidade ganha um fórum: tópico com título e corpo, respostas em
-- árvore (até 6 níveis), voto pra cima e pra baixo, fixar, trancar e
-- enquete. Regras em lib/topics.ts.
--
-- Autor de tópico e de resposta mora em memberId (dono da linha, como em
-- posts): no export entra como linha da pessoa e na exclusão da conta o
-- conteúdo sai. Tópico ou resposta que já tem resposta de outra pessoa não é
-- apagado: vira "[apagado]" (deletedAt, corpo vazio, memberId nulo) pra
-- árvore dos outros continuar de pé. Moderação usa removedAt/removedBy e
-- também mantém a árvore.

CREATE TABLE community_topics (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "communityId" INTEGER NOT NULL REFERENCES communities("id") ON DELETE CASCADE,
  "memberId" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "title" TEXT NOT NULL CHECK (char_length("title") BETWEEN 5 AND 140),
  "body" TEXT NOT NULL DEFAULT '' CHECK (char_length("body") <= 10000),
  "flair" TEXT CHECK ("flair" IS NULL OR char_length("flair") BETWEEN 1 AND 24),
  "kind" TEXT NOT NULL DEFAULT 'discussao' CHECK ("kind" IN ('discussao', 'pergunta', 'enquete', 'mostra')),
  "pinnedAt" TEXT,
  "lockedAt" TEXT,
  "removedAt" TEXT,
  "removedBy" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "deletedAt" TEXT,
  "acceptedReplyId" INTEGER,
  "score" INTEGER NOT NULL DEFAULT 0,
  "replyCount" INTEGER NOT NULL DEFAULT 0,
  "lastActivityAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "editedAt" TEXT
);
CREATE INDEX idx_topics_activity ON community_topics ("communityId", "lastActivityAt" DESC);
CREATE INDEX idx_topics_score ON community_topics ("communityId", "score" DESC);
CREATE INDEX idx_topics_created ON community_topics ("communityId", "createdAt" DESC);
CREATE INDEX idx_topics_member ON community_topics ("memberId");

-- resposta em árvore: parentId nulo = resposta direta ao tópico. depth 1..6;
-- quem responde a uma de nível 6 vira irmã dela (lib/topics.ts)
CREATE TABLE topic_replies (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "topicId" INTEGER NOT NULL REFERENCES community_topics("id") ON DELETE CASCADE,
  "parentId" INTEGER REFERENCES topic_replies("id") ON DELETE CASCADE,
  "memberId" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "depth" INTEGER NOT NULL DEFAULT 1 CHECK ("depth" BETWEEN 1 AND 6),
  "body" TEXT NOT NULL CHECK (char_length("body") <= 5000),
  "score" INTEGER NOT NULL DEFAULT 0,
  "removedAt" TEXT,
  "removedBy" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "deletedAt" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "editedAt" TEXT
);
CREATE INDEX idx_topic_replies_topic ON topic_replies ("topicId", "createdAt");
CREATE INDEX idx_topic_replies_parent ON topic_replies ("parentId");
CREATE INDEX idx_topic_replies_member ON topic_replies ("memberId");

ALTER TABLE community_topics
  ADD CONSTRAINT "community_topics_acceptedReplyId_fkey"
  FOREIGN KEY ("acceptedReplyId") REFERENCES topic_replies("id") ON DELETE SET NULL;

-- um voto por pessoa por alvo; o score do alvo é a soma, recalculada na
-- mesma transação do voto. Voto não dá XP nem rep.
CREATE TABLE topic_votes (
  "targetType" TEXT NOT NULL CHECK ("targetType" IN ('topic', 'reply')),
  "targetId" INTEGER NOT NULL,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "value" INTEGER NOT NULL CHECK ("value" IN (-1, 1)),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("targetType", "targetId", "memberId")
);
CREATE INDEX idx_topic_votes_member ON topic_votes ("memberId");

-- enquete: 2 a 6 opções, um voto por pessoa por tópico
CREATE TABLE topic_poll_options (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "topicId" INTEGER NOT NULL REFERENCES community_topics("id") ON DELETE CASCADE,
  "label" TEXT NOT NULL CHECK (char_length("label") BETWEEN 1 AND 80),
  "position" INTEGER NOT NULL
);
CREATE INDEX idx_topic_poll_options_topic ON topic_poll_options ("topicId", "position");

CREATE TABLE topic_poll_votes (
  "topicId" INTEGER NOT NULL REFERENCES community_topics("id") ON DELETE CASCADE,
  "optionId" INTEGER NOT NULL REFERENCES topic_poll_options("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("topicId", "memberId")
);
CREATE INDEX idx_topic_poll_votes_option ON topic_poll_votes ("optionId");

-- denúncia de tópico e de resposta entra na fila única (032)
DO $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT c.conname FROM pg_constraint c
    WHERE c.conrelid = 'reports'::regclass AND c.contype = 'c'
      AND pg_get_constraintdef(c.oid) LIKE '%targetType%'
  LOOP
    EXECUTE format('ALTER TABLE reports DROP CONSTRAINT %I', r.conname);
  END LOOP;
END $$;
ALTER TABLE reports ADD CONSTRAINT "reports_targetType_check" CHECK ("targetType" IN
  ('post', 'comment', 'member', 'community', 'depoimento', 'dm', 'encontro', 'topic', 'topic_reply'));
