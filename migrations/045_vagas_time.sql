-- 045 — vagas de time (spec 046, onda 3).
--
-- Formar time era o gargalo do teardown: o board da edição só anunciava
-- "procuro time" e o convite dependia de alguém adivinhar o @. Aqui o time
-- abre vaga com área ("procuro design"), a pessoa se candidata com uma intro
-- curta, e o aceite do time vira convite (team_invites, migration 016): a
-- linha de team_members continua nascendo só no aceite do convidado, então
-- arquivo, júri, certificado e voto seguem lendo "está no time" como antes.
--
-- `area` é chave de AREA_KEYS (lib/areas.ts), o mesmo vocabulário de
-- "posso ajudar com" do perfil: a lista mora no código, então não há CHECK
-- aqui (chave nova não pede migration).

CREATE TABLE team_openings (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "teamId" INTEGER NOT NULL REFERENCES teams("id") ON DELETE CASCADE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "area" TEXT NOT NULL,
  -- o que o time procura, em uma frase (mesmo teto da intro da candidatura)
  "intro" TEXT NOT NULL CHECK (char_length("intro") BETWEEN 1 AND 280),
  -- quem abriu; some com a conta, a vaga fica (é do time, não da pessoa)
  "createdBy" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "status" TEXT NOT NULL DEFAULT 'aberta'
    CHECK ("status" IN ('aberta', 'preenchida', 'fechada')),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_team_openings_edition ON team_openings ("hackathonId", "status", "createdAt");
CREATE INDEX idx_team_openings_team ON team_openings ("teamId", "status");

-- uma candidatura por pessoa por vaga; recusada/retirada pode voltar (a
-- pessoa reaproveita a linha em vez de criar outra)
CREATE TABLE opening_applications (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "openingId" INTEGER NOT NULL REFERENCES team_openings("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "intro" TEXT NOT NULL CHECK (char_length("intro") BETWEEN 1 AND 280),
  "status" TEXT NOT NULL DEFAULT 'enviada'
    CHECK ("status" IN ('enviada', 'aceita', 'recusada', 'retirada')),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "respondedAt" TEXT,
  UNIQUE ("openingId", "memberId")
);
CREATE INDEX idx_opening_applications_opening ON opening_applications ("openingId", "status");
CREATE INDEX idx_opening_applications_member ON opening_applications ("memberId", "status");

-- "bora fazer junto" (estudo 045, §Do encontro ao time): sinal mútuo e
-- silencioso. Um sinal sozinho não avisa ninguém; quando os dois marcam na
-- mesma edição, o app chama o convite, cria o time (quando nenhum tem) ou
-- deixa a conexão. peerId é o outro lado da relação (PEER_COLUMNS): conta
-- excluída leva o sinal dos dois lados.
CREATE TABLE team_up_signals (
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "peerId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("memberId", "peerId", "hackathonId"),
  CHECK ("memberId" <> "peerId")
);
CREATE INDEX idx_team_up_signals_peer ON team_up_signals ("peerId", "hackathonId");
