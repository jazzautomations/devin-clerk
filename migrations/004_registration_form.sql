-- 004 — formulário de inscrição por edição, consentimento LGPD e limite de
-- vagas com fila de espera (spec 033 US1, FR-001, FR-002, FR-009).
-- Substitui o Google Forms: a edição define as perguntas, o inscrito
-- responde uma vez, o consentimento fica registrado com versão e IP.

-- vagas: NULL = sem limite. Conta só inscrição 'approved'.
ALTER TABLE hackathons ADD COLUMN "capacity" INTEGER
  CHECK ("capacity" IS NULL OR "capacity" >= 0);

-- fila de espera: status 'waitlist' em ordem de waitlistedAt; promotedAt
-- marca quem saiu da fila por vaga liberada (hook do aviso — frente D lê).
-- O status era TEXT sem CHECK (approved/pending/rejected); agora é fechado.
-- NOT VALID: não revalida linhas antigas no deploy, mas vale pra toda escrita nova.
ALTER TABLE registrations ADD COLUMN "waitlistedAt" TEXT;
ALTER TABLE registrations ADD COLUMN "promotedAt" TEXT;
ALTER TABLE registrations ADD CONSTRAINT registrations_status_check
  CHECK ("status" IN ('approved', 'pending', 'rejected', 'waitlist')) NOT VALID;
CREATE INDEX idx_registrations_waitlist
  ON registrations ("hackathonId", "waitlistedAt", "id") WHERE "status" = 'waitlist';
CREATE INDEX idx_registrations_promoted
  ON registrations ("hackathonId", "promotedAt") WHERE "promotedAt" IS NOT NULL;

-- pergunta "viva" da edição (estado atual). Editar texto/opções de uma
-- pergunta que já tem resposta sobe a version; o texto antigo fica
-- congelado em edition_question_versions e a resposta aponta pra ele.
CREATE TABLE edition_questions (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "version" INTEGER NOT NULL DEFAULT 1,
  "kind" TEXT NOT NULL
    CHECK ("kind" IN ('short_text', 'long_text', 'single', 'multi', 'yes_no')),
  "label" TEXT NOT NULL,
  "options" TEXT NOT NULL DEFAULT '[]',
  "required" INTEGER NOT NULL DEFAULT 0,
  "position" INTEGER NOT NULL DEFAULT 0,
  "archived" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "updatedAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_edition_questions_hackathon
  ON edition_questions ("hackathonId", "archived", "position");

CREATE TABLE edition_question_versions (
  "questionId" INTEGER NOT NULL REFERENCES edition_questions("id") ON DELETE CASCADE,
  "version" INTEGER NOT NULL,
  "kind" TEXT NOT NULL,
  "label" TEXT NOT NULL,
  "options" TEXT NOT NULL DEFAULT '[]',
  "required" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("questionId", "version")
);

-- uma resposta por pergunta por inscrição; cancelar a inscrição apaga as
-- respostas junto (CASCADE) — dado pessoal não fica órfão.
CREATE TABLE registration_answers (
  "registrationId" INTEGER NOT NULL REFERENCES registrations("id") ON DELETE CASCADE,
  "questionId" INTEGER NOT NULL,
  "questionVersion" INTEGER NOT NULL,
  "value" TEXT NOT NULL,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("registrationId", "questionId"),
  FOREIGN KEY ("questionId", "questionVersion")
    REFERENCES edition_question_versions ("questionId", "version") ON DELETE CASCADE
);
CREATE INDEX idx_registration_answers_question ON registration_answers ("questionId");

-- consentimento LGPD (FR-002): uma linha por aceite, com a versão do termo,
-- o texto exato da finalidade (organização + parceiros nomeados na hora) e o IP.
CREATE TABLE consents (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "termsVersion" TEXT NOT NULL,
  "purpose" TEXT NOT NULL,
  "acceptedAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "ip" TEXT
);
CREATE INDEX idx_consents_member_hackathon ON consents ("memberId", "hackathonId");
