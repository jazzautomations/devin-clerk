-- 015 — termos do evento (roadmap 037 Onda 1 #3, #6, #7; pesquisa 035
-- itens 4, 8, 9 e riscos 3–4): uso de imagem separado e revogável, idade
-- mínima por edição com responsável pra menor, restrição alimentar com
-- relatório pro buffet, código de conduta versionado e canal de incidentes.

-- configuração por edição. Sem linha = padrão (18+, sem pergunta de dieta,
-- código de conduta padrão). minAge < 18 = a edição aceita menor, que
-- precisa de responsável (nome, e-mail e aceite declarado).
CREATE TABLE edition_terms (
  "hackathonId" TEXT PRIMARY KEY REFERENCES hackathons("id") ON DELETE CASCADE,
  "minAge" INTEGER NOT NULL DEFAULT 18 CHECK ("minAge" BETWEEN 14 AND 99),
  "dietEnabled" INTEGER NOT NULL DEFAULT 0,
  "updatedBy" INTEGER REFERENCES members("id"),
  "updatedAt" TEXT NOT NULL DEFAULT sqlite_now()
);

-- código de conduta congelado por versão: o aceite aponta pra versão que a
-- pessoa leu (mesma ideia de edition_question_versions). A versão 1 do
-- texto padrão é gravada no primeiro aceite ou na primeira edição do texto.
CREATE TABLE edition_conduct_versions (
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "version" INTEGER NOT NULL,
  "text" TEXT NOT NULL,
  "createdBy" INTEGER REFERENCES members("id"),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("hackathonId", "version")
);

-- termos aceitos na inscrição (1:1 com a inscrição). Cancelar a inscrição
-- apaga junto (CASCADE por registrationId); excluir a conta apaga pelo
-- memberId (lib/privacy trata memberId como dono). Dado mínimo:
--   birthDate — só a data declarada, pra provar a checagem de idade; o
--     painel mostra a idade no evento, nunca a data;
--   guardian* — só pra menor; o aceite é declarado pelo inscrito e o
--     responsável recebe e-mail avisando (guardianEmailStatus guarda o
--     desfecho do driver: sent/skipped/failed);
--   diet/allergies — só quando a edição liga a pergunta.
CREATE TABLE registration_terms (
  "registrationId" INTEGER PRIMARY KEY REFERENCES registrations("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "birthDate" TEXT NOT NULL,
  "ageAtEvent" INTEGER NOT NULL,
  "conductVersion" INTEGER NOT NULL,
  "conductAcceptedAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "guardianName" TEXT,
  "guardianEmail" TEXT,
  "guardianDeclaredAt" TEXT,
  "guardianEmailStatus" TEXT CHECK ("guardianEmailStatus" IN ('sent', 'skipped', 'failed')),
  "diet" TEXT NOT NULL DEFAULT '[]',
  "allergies" TEXT,
  "allergySevere" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  FOREIGN KEY ("hackathonId", "conductVersion")
    REFERENCES edition_conduct_versions ("hackathonId", "version")
);
CREATE INDEX idx_registration_terms_hackathon ON registration_terms ("hackathonId");
CREATE INDEX idx_registration_terms_member ON registration_terms ("memberId");

-- uso de imagem: histórico append-only (prova). Estado atual = última
-- linha de (membro, edição); sem linha = não autorizou. Nunca vem marcado
-- e recusar não impede a inscrição.
CREATE TABLE image_consents (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "granted" INTEGER NOT NULL CHECK ("granted" IN (0, 1)),
  "purpose" TEXT NOT NULL,
  "source" TEXT NOT NULL CHECK ("source" IN ('inscricao', 'perfil', 'edicao')),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_image_consents_member_hackathon ON image_consents ("memberId", "hackathonId", "id");
CREATE INDEX idx_image_consents_hackathon ON image_consents ("hackathonId");

-- responsáveis de conduta: gente da equipe da edição que o organizador
-- autoriza a ver e tratar incidentes (staff não vê por padrão)
CREATE TABLE edition_conduct_handlers (
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "grantedBy" INTEGER REFERENCES members("id"),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("hackathonId", "memberId")
);

-- denúncias. reporterId NULL = anônima: nem membro nem IP são gravados
-- (o rate-limit vive só em memória). Quem pede exclusão da conta tem o
-- autor anonimizado (reporterId e contato viram NULL), a denúncia fica.
CREATE TABLE incidents (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "reporterId" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "kind" TEXT NOT NULL
    CHECK ("kind" IN ('assedio', 'discriminacao', 'seguranca', 'saude', 'outro')),
  "description" TEXT NOT NULL,
  "location" TEXT,
  "occurredAt" TEXT,
  "contact" TEXT,
  "status" TEXT NOT NULL DEFAULT 'aberto'
    CHECK ("status" IN ('aberto', 'em_andamento', 'resolvido')),
  "internalNote" TEXT,
  "updatedBy" INTEGER REFERENCES members("id"),
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "updatedAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_incidents_hackathon ON incidents ("hackathonId", "status", "id");
CREATE INDEX idx_incidents_reporter ON incidents ("reporterId") WHERE "reporterId" IS NOT NULL;
