-- 057 — espaços da comunidade (spec 046, onda 6): o mural se divide em
-- espaços estilo Circle (geral, ajuda, vagas, mostra). Quem posta escolhe o
-- espaço; dono e organizadores criam, renomeiam, ordenam e arquivam em
-- /comunidade/[slug]/espacos. Regras em lib/communitySpaces.ts.
--
-- postPolicy organizacao = só dono e organizadores postam (o espaço de
-- avisos do time); membros = qualquer membro. Arquivar esconde o espaço
-- do seletor e mantém os posts (o post guarda spaceId).
--
-- O trigger dá os 4 espaços padrão pra toda comunidade nova; o INSERT logo
-- abaixo dá os mesmos 4 pras que já existiam, e os posts antigos do mural
-- caem no geral.

CREATE TABLE IF NOT EXISTS community_spaces (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "communityId" INTEGER NOT NULL REFERENCES communities("id") ON DELETE CASCADE,
  "slug" TEXT NOT NULL CHECK ("slug" ~ '^[a-z0-9-]{2,30}$'),
  "name" TEXT NOT NULL CHECK (char_length("name") BETWEEN 1 AND 40),
  "description" TEXT CHECK ("description" IS NULL OR char_length("description") <= 200),
  "postPolicy" TEXT NOT NULL DEFAULT 'membros' CHECK ("postPolicy" IN ('membros','organizacao')),
  "position" INTEGER NOT NULL DEFAULT 0,
  "archivedAt" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  UNIQUE ("communityId", "slug")
);
CREATE INDEX IF NOT EXISTS idx_community_spaces_community ON community_spaces ("communityId", "position");

ALTER TABLE posts ADD COLUMN IF NOT EXISTS "spaceId" INTEGER REFERENCES community_spaces("id") ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_posts_space ON posts ("spaceId");

-- os 4 padrão, pra toda comunidade que já existia (e pra qualquer uma que
-- tenha perdido um deles — ON CONFLICT torna a migration reexecutável)
INSERT INTO community_spaces ("communityId", "slug", "name", "description", "position")
SELECT c.id, s.slug, s.name, s.description, s.position
FROM communities c
CROSS JOIN (VALUES
  ('geral', 'geral', 'o que vale pra comunidade inteira', 0),
  ('ajuda', 'ajuda', 'o que está travando você', 1),
  ('vagas', 'vagas', 'vagas e oportunidades', 2),
  ('mostra', 'mostra', 'mostra o que você fez', 3)
) AS s(slug, name, description, position)
ON CONFLICT ("communityId", "slug") DO NOTHING;

-- post antigo do mural cai no geral (post novo sem espaço também: lib)
UPDATE posts p
SET "spaceId" = cs.id
FROM community_spaces cs
WHERE p."communityId" = cs."communityId" AND cs."slug" = 'geral' AND p."spaceId" IS NULL;

CREATE OR REPLACE FUNCTION community_default_spaces() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO community_spaces ("communityId", "slug", "name", "description", "position")
  VALUES
    (NEW.id, 'geral', 'geral', 'o que vale pra comunidade inteira', 0),
    (NEW.id, 'ajuda', 'ajuda', 'o que está travando você', 1),
    (NEW.id, 'vagas', 'vagas', 'vagas e oportunidades', 2),
    (NEW.id, 'mostra', 'mostra', 'mostra o que você fez', 3)
  ON CONFLICT ("communityId", "slug") DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS communities_default_spaces ON communities;
CREATE TRIGGER communities_default_spaces
  AFTER INSERT ON communities
  FOR EACH ROW EXECUTE FUNCTION community_default_spaces();
