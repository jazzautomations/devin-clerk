-- 032 — bloqueio, silêncio e denúncia numa fila só (spec 046, onda 0).
--
-- Relação entre duas pessoas segue a convenção de lib/privacy.ts: memberId
-- é o dono da linha, blockedId/mutedId é o outro lado. Bloquear vale nos
-- dois sentidos pra quem lê (lib/blocks.ts); silenciar só esconde pra quem
-- silenciou. Ninguém é avisado de nenhum dos dois.

CREATE TABLE member_blocks (
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "blockedId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("memberId", "blockedId"),
  CHECK ("memberId" <> "blockedId")
);
CREATE INDEX idx_member_blocks_blocked ON member_blocks ("blockedId");

CREATE TABLE member_mutes (
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "mutedId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("memberId", "mutedId"),
  CHECK ("memberId" <> "mutedId")
);
CREATE INDEX idx_member_mutes_muted ON member_mutes ("mutedId");

-- Denúncia de qualquer coisa. Vai pra quem modera o espaço: communityId
-- preenchido = dono e organizadores da comunidade; hackathonId = quem trata
-- incidentes da edição; os dois nulos = admin global (que vê tudo).
-- reporterId fica nulo quando quem denunciou exclui a conta: a denúncia
-- continua, sem autor. snapshot é a cópia do texto denunciado no momento,
-- pra a fila não depender do conteúdo continuar no ar. targetMemberId é o
-- autor do que foi denunciado: ninguém lê nem resolve denúncia contra si, e
-- quando o autor modera o espaço a denúncia já nasce na fila do admin.
CREATE TABLE reports (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "targetType" TEXT NOT NULL CHECK ("targetType" IN ('post', 'comment', 'member', 'community', 'depoimento', 'dm', 'encontro')),
  "targetId" TEXT NOT NULL,
  "reporterId" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "targetMemberId" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "reason" TEXT NOT NULL CHECK (length("reason") <= 500),
  "snapshot" TEXT CHECK (length("snapshot") <= 2000),
  "communityId" INTEGER REFERENCES communities("id") ON DELETE CASCADE,
  "hackathonId" TEXT REFERENCES hackathons("id") ON DELETE CASCADE,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "resolvedAt" TEXT,
  "resolvedBy" INTEGER REFERENCES members("id"),
  "resolution" TEXT
);
-- a mesma pessoa não abre duas denúncias do mesmo alvo enquanto uma está aberta
CREATE UNIQUE INDEX idx_reports_open_once ON reports ("reporterId", "targetType", "targetId") WHERE "resolvedAt" IS NULL;
CREATE INDEX idx_reports_community ON reports ("communityId", "resolvedAt");
CREATE INDEX idx_reports_hackathon ON reports ("hackathonId", "resolvedAt");
CREATE INDEX idx_reports_open ON reports ("resolvedAt", "id");

-- Notificação ganha o id de quem agiu. actorUsername continua (texto
-- congelado), mas silenciar e bloquear filtram por actorId: trocar o @ não
-- traz de volta as notificações de quem foi silenciado ou bloqueado.
ALTER TABLE notifications ADD COLUMN "actorId" INTEGER REFERENCES members("id") ON DELETE SET NULL;
UPDATE notifications n SET "actorId" = m."id" FROM members m WHERE m."username" = n."actorUsername";
UPDATE notifications n SET "actorId" = r."memberId" FROM username_redirects r
  WHERE n."actorId" IS NULL AND r."oldUsername" = n."actorUsername";
CREATE INDEX idx_notifications_actor ON notifications ("actorId");

-- As denúncias de comunidade (027) passam pra fila nova. Denúncia contra a
-- comunidade inteira é do admin (o dono não modera denúncia contra si), então
-- communityId fica nulo e o alvo vai em targetId. Duplicata aberta da mesma
-- pessoa vira uma linha só. community_reports fica, mas ninguém mais grava nela.
INSERT INTO reports ("targetType", "targetId", "reporterId", "reason", "snapshot", "createdAt", "resolvedAt", "resolution")
SELECT 'community', r."communityId"::text, r."memberId", left(r."reason", 500), left(c."name", 2000),
       r."createdAt", r."resolvedAt", CASE WHEN r."resolvedAt" IS NOT NULL THEN 'comunidade escondida' END
FROM community_reports r JOIN communities c ON c."id" = r."communityId"
ORDER BY r."id"
ON CONFLICT DO NOTHING;

