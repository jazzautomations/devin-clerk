-- 046 — comunidade dona do próprio espaço (spec 046, onda 3).
--
-- Dono e organizadores moderam a comunidade sem depender do admin global:
-- fila de denúncia (032, roteada por communityId), aviso editado e apagado,
-- membro removido e impedido de voltar, comunidade excluída e posse
-- transferida. Toda ação dessas fica registrada em community_mod_log.

-- Excluir comunidade é soft: com deletedAt preenchido ela some das listas e
-- a página dá 404. Hackathon mantém communityId (o histórico do evento não
-- some com a comunidade). hidden também vai a 1, pra nenhuma consulta antiga
-- que ainda leia communities mostrar o espaço.
ALTER TABLE communities ADD COLUMN IF NOT EXISTS "deletedAt" TEXT;

-- "impedir de voltar": quem foi removido com ban não entra nem segue de novo
-- (lib/communities.ts e lib/follows.ts devolvem 403). Remover o ban libera.
CREATE TABLE community_bans (
  "communityId" INTEGER NOT NULL REFERENCES communities("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "reason" TEXT CHECK ("reason" IS NULL OR length("reason") <= 300),
  "createdBy" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  PRIMARY KEY ("communityId", "memberId")
);
CREATE INDEX idx_community_bans_member ON community_bans ("memberId");

-- quem fez o quê, quando. actorId nulo = conta excluída (a ação continua no
-- histórico da comunidade, sem autor). action é um código curto
-- (lib/communityModeration.ts traduz pra tela); target é o alvo em texto.
CREATE TABLE community_mod_log (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "communityId" INTEGER NOT NULL REFERENCES communities("id") ON DELETE CASCADE,
  "actorId" INTEGER REFERENCES members("id") ON DELETE SET NULL,
  "action" TEXT NOT NULL,
  "target" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_community_mod_log_community ON community_mod_log ("communityId", "id" DESC);
