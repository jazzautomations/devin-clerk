-- 050 — encontros na edição (spec 046, onda 5; desenho da spec 045).
--
-- O organizador liga os encontros por edição ("encountersOn") e, se quiser,
-- as missões ("encounterMissionsOn", desligadas por padrão: sugestão, nunca
-- obrigação). Quem fez check-in e aceitou aparece com um código de 5
-- caracteres e um QR do próprio bicho; o encontro só conta quando os DOIS
-- confirmam. Um encontro por par por edição.
--
-- Chaves de 5 caracteres sem 0, O, 1 e I (quem lê o crachá impresso não
-- confunde). O código é da edição: regenerar invalida o antigo (UNIQUE por
-- hackathonId) e pausar devolve a mesma resposta genérica de "não achei".
--
-- team_up_signals ("bora fazer junto") NÃO nasce aqui: é da migration 045
-- (vagas de time) e o encontro reusa a tabela e a rota que já existem.

ALTER TABLE hackathons ADD COLUMN "encountersOn" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE hackathons ADD COLUMN "encounterMissionsOn" INTEGER NOT NULL DEFAULT 0;

CREATE TABLE edition_meet_codes (
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "code" TEXT NOT NULL CHECK ("code" ~ '^[2-9A-HJ-NP-Z]{5}$'),
  -- canal de contato que aparece pro outro lado depois do encontro confirmado
  -- (lido do perfil na hora, nunca copiado)
  "contactChannel" TEXT NOT NULL DEFAULT 'linkedin'
    CHECK ("contactChannel" IN ('linkedin', 'github', 'email')),
  -- aceite próprio de "encontros na edição" (revogar = DELETE da linha)
  "optedInAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "pausedAt" TEXT,
  -- aceite próprio "pode me mostrar como estreante" (missão primeira viagem)
  "newcomerOptIn" INTEGER NOT NULL DEFAULT 0 CHECK ("newcomerOptIn" IN (0, 1)),
  -- aceite próprio de intros quinzenais (fora do evento, onda 6)
  "introOptIn" INTEGER NOT NULL DEFAULT 0 CHECK ("introOptIn" IN (0, 1)),
  PRIMARY KEY ("hackathonId", "memberId"),
  UNIQUE ("hackathonId", "code")
);
CREATE INDEX idx_meet_codes_member ON edition_meet_codes ("memberId");

CREATE TABLE encounters (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  -- par em ordem crescente: um encontro por par por edição, sem dupla linha
  "lowId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "highId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "initiatorId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "status" TEXT NOT NULL DEFAULT 'pending'
    CHECK ("status" IN ('pending', 'confirmed', 'declined', 'expired')),
  -- zona do evento definida pelo organizador (nunca GPS); reservada na v1
  "zone" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  "confirmedAt" TEXT,
  CHECK ("lowId" < "highId"),
  UNIQUE ("hackathonId", "lowId", "highId")
);
CREATE INDEX idx_encounters_low ON encounters ("lowId", "hackathonId");
CREATE INDEX idx_encounters_high ON encounters ("highId", "hackathonId");

-- o que cada lado respondeu: carta usada, profundidade e nota privada.
-- "papo rápido" × "fomos além do oi" só conta profundidade quando os dois
-- marcam "além" (lib/missions.ts, mutualDepth).
CREATE TABLE encounter_sides (
  "encounterId" INTEGER NOT NULL REFERENCES encounters("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "cardKey" TEXT,
  "depth" TEXT CHECK ("depth" IN ('rapido', 'alem')),
  "note" TEXT CHECK ("note" IS NULL OR char_length("note") <= 280),
  "hiddenAt" TEXT,
  PRIMARY KEY ("encounterId", "memberId")
);

-- 3 recusas pro mesmo alvo travam o par na edição (quem pediu não sabe)
CREATE TABLE encounter_declines (
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "peerId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "count" INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY ("hackathonId", "memberId", "peerId"),
  CHECK ("memberId" <> "peerId")
);

-- "apresentei X a Y" (missão ponte): conta quando X e Y confirmam encontro
-- entre si depois da apresentação
CREATE TABLE introductions (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id") ON DELETE CASCADE,
  "memberId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "peerId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "recipientId" INTEGER NOT NULL REFERENCES members("id") ON DELETE CASCADE,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now(),
  UNIQUE ("hackathonId", "memberId", "peerId", "recipientId"),
  CHECK ("peerId" <> "recipientId" AND "memberId" <> "peerId" AND "memberId" <> "recipientId")
);
CREATE INDEX idx_introductions_member ON introductions ("memberId", "hackathonId");
