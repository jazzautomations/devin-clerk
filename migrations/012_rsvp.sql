-- 012 — RSVP anti-no-show (roadmap 037 Onda 1 #1; pesquisa 035 #1).
-- Comparecimento de evento grátis é ~50%: no D-7 cada aprovado recebe
-- "confirmo / não vou"; sem resposta até o fim do D-3 a vaga volta pra
-- fila. Lembretes D-1 (logística) e H-2 (endereço + ingresso) só pra quem
-- confirmou. Tudo desligado por padrão (rsvpEnabled = 0).

ALTER TABLE hackathons ADD COLUMN "rsvpEnabled" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE hackathons ADD COLUMN "rsvpOpensDaysBefore" INTEGER NOT NULL DEFAULT 7
  CHECK ("rsvpOpensDaysBefore" BETWEEN 1 AND 60);
ALTER TABLE hackathons ADD COLUMN "rsvpDeadlineDaysBefore" INTEGER NOT NULL DEFAULT 3
  CHECK ("rsvpDeadlineDaysBefore" BETWEEN 0 AND 59);
-- sobrevenda: só pra decisão de aprovação, e só com RSVP ligado
ALTER TABLE hackathons ADD COLUMN "overbookPercent" INTEGER NOT NULL DEFAULT 0
  CHECK ("overbookPercent" BETWEEN 0 AND 100);

-- rsvpStatus NULL = ainda não convidado (ou RSVP desligado). Na linha viva
-- só aparecem 'pending' e 'confirmed': quem recusa ou expira tem a
-- inscrição liberada (a linha sai, como no cancelamento) e o desfecho fica
-- em rsvp_releases. rsvpDeadlineAt é o prazo individual (o do convite do
-- D-7, ou 24h pra quem sai da fila depois). rsvpReminderStage: 0 nada,
-- 1 = D-1 enviado, 2 = H-2 enviado — o UPDATE condicional é a trava.
ALTER TABLE registrations ADD COLUMN "rsvpStatus" TEXT
  CHECK ("rsvpStatus" IN ('pending','confirmed','declined','expired'));
ALTER TABLE registrations ADD COLUMN "rsvpAt" TEXT;
ALTER TABLE registrations ADD COLUMN "rsvpDeadlineAt" TEXT;
ALTER TABLE registrations ADD COLUMN "rsvpReminderStage" INTEGER NOT NULL DEFAULT 0;
CREATE INDEX idx_registrations_rsvp ON registrations ("hackathonId", "rsvpStatus")
  WHERE "rsvpStatus" IS NOT NULL;

-- vaga liberada pelo RSVP. registrationId sem FK de propósito: a linha de
-- registrations já foi apagada; é por ele que o link antigo reconhece
-- "você já recusou" (idempotência do /rsvp/[token]).
CREATE TABLE rsvp_releases (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "registrationId" INTEGER NOT NULL UNIQUE,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id"),
  "memberId" INTEGER NOT NULL REFERENCES members("id"),
  "outcome" TEXT NOT NULL CHECK ("outcome" IN ('declined','expired')),
  "wasConfirmed" INTEGER NOT NULL DEFAULT 0,
  "at" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_rsvp_releases_hackathon ON rsvp_releases ("hackathonId");
CREATE INDEX idx_rsvp_releases_member ON rsvp_releases ("memberId");

-- log das mensagens do RSVP (convite, D-1, H-2, reenvio manual) por canal —
-- auditoria pro organizador e freio do reenvio manual
CREATE TABLE rsvp_messages (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hackathonId" TEXT NOT NULL REFERENCES hackathons("id"),
  "memberId" INTEGER NOT NULL REFERENCES members("id"),
  "registrationId" INTEGER NOT NULL,
  "kind" TEXT NOT NULL CHECK ("kind" IN ('invite','d1','h2','resend')),
  "channel" TEXT NOT NULL CHECK ("channel" IN ('inapp','email','whatsapp')),
  "status" TEXT NOT NULL CHECK ("status" IN ('sent','failed','skipped')),
  "error" TEXT,
  "createdAt" TEXT NOT NULL DEFAULT sqlite_now()
);
CREATE INDEX idx_rsvp_messages_reg ON rsvp_messages ("registrationId", "kind");
